def bits(s):
    v = 0
    for row in s.split():
        for ch in row: v = (v << 1) | (ch == 'X')
    return v
table = [0] * 0x85
for k, s in G.items():
    table[k if isinstance(k, int) else ord(k)] = bits(s)
for c in range(ord('a'), ord('z') + 1):
    if chr(c) not in G: table[c] = table[c - 32]
out = os.path.join(os.path.dirname(__file__), '..', 'FlowerDisplay', 'font3x5.h')
with open(out, 'w') as f:
    f.write('// AUTO-GENERATED by tools/gen_font.py - 3x5 glyphs, 15 bits each (row-major, MSB = top-left)\n')
    f.write('#pragma once\n#include <stdint.h>\n\nstatic const uint16_t FONT3X5[0x85] = {\n')
    for i in range(0, len(table), 8):
        f.write('  ' + ', '.join('0x%04X' % v for v in table[i:i+8]) + ',\n')
    f.write('};\n\nstatic inline uint16_t glyph3x5(uint8_t ch) { return ch < 0x85 ? FONT3X5[ch] : 0; }\n')
print('wrote', os.path.normpath(out))
